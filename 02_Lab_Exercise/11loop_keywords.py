# A simple for loop that prints numbers from 0 to 4
for i in range(5):
    print(i)


# A for loop that stops when i equals 2
for i in range(5):
    if i == 2:
        break  # Exit the loop completely when i is 2
    print(i)


# A for loop that skips printing when i equals 2
for i in range(5):
    if i == 2:
        continue  # Skip this iteration when i is 2
    print(i)


