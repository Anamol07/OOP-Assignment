# Initializing the variable to store the sum of squares
sum_of_squares = 0

# Looping through numbers 1 to 5 
for i in range(1, 6):
    # Adding the square of each number to sum_of_squares
    sum_of_squares += i ** 2  # Equivalent to sum_of_squares = sum_of_squares + (i * i)

# Printing the final result
print(sum_of_squares)

