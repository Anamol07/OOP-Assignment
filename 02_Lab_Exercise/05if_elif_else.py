# Assigning marks to a variable
marks = 80

# Checking if marks are less than 50
if marks < 50:
    print("You failed") 

# Checking if marks are less than 60
elif marks < 60:
    print("You passed")  

# Checking if marks are less than 70
elif marks < 70:
    print("You got a good marks")  

# If none of the above are True, this will run
else:
    print("You got a excellent marks")