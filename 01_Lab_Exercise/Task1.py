# Assign an integer value to the variable
my_int = 5

# Assign a floating-point number to the variable
my_float = 5.5

# Assign a boolean value to the variable
my_bool = True

# Print the values 
print(f"{my_int},{my_float},{my_bool}")

# Cast my_int to float
my_int_float = float(my_int)

# Cast my_float to integer
my_float_int = int(my_float)

# Cast my_bool to integer
my_bool_int = int(my_bool)

# Print all the variables
print(f"my_int_float:{my_int_float},my_float_int: {my_float_int},my_bool_int:{my_bool_int}")