# Modifying String
# Assigning value to variable
my_string = " This Class covers OOP"

# Printing my_string variable
print(my_string)

# Converting to uppercase and assigning to new variable
my_uppercase_string = my_string.upper()

# Printing uppercase version of the string
print(my_uppercase_string)

# Converting to lowercase and assigning to new variable
my_lowercase_string = my_string.lower()

# Printing lowercase version of the string
print(my_lowercase_string)

# Replacing "OOP" with "Object Oriented Programming"
my_new_string = my_string.replace("OOP", "Object Oriented Programming")

# Printing modified string with replacement
print(my_new_string)

# Getting the length of the string
my_string_length = len(my_string)

# Printing the length of the original string
print(my_string_length)